/**
 * Regenerates lib/imageDimensions.ts — the intrinsic pixel size of every image
 * under public/projects/. ZoomableImage reads it to reserve layout space, so
 * lazy-loaded figures don't shift the page as they arrive.
 *
 * Run after adding or replacing project imagery:  node scripts/gen-image-dimensions.mjs
 */
import { readdir, readFile, writeFile } from "node:fs/promises";
import { join, relative, extname } from "node:path";
import { execFileSync } from "node:child_process";
import imageSize from "image-size";

const PUBLIC_DIR = "public";
const SCAN_DIR = join(PUBLIC_DIR, "projects");
const OUT_FILE = join("lib", "imageDimensions.ts");
const EXTENSIONS = new Set([".png", ".jpg", ".jpeg", ".webp", ".gif"]);

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else yield full;
  }
}

/**
 * Files git ignores never ship, so they must not appear in the map — otherwise a
 * checkout of this repo produces a different file than the one committed. This also
 * keeps redacted people-media out of the public repo by name as well as by content.
 */
function isGitIgnored(file) {
  try {
    execFileSync("git", ["check-ignore", "-q", file], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

const entries = [];
for await (const file of walk(SCAN_DIR)) {
  if (!EXTENSIONS.has(extname(file).toLowerCase())) continue;
  if (isGitIgnored(file)) continue;
  try {
    const { width, height } = imageSize(await readFile(file));
    if (!width || !height) continue;
    entries.push([`/${relative(PUBLIC_DIR, file).split("\\").join("/")}`, width, height]);
  } catch {
    console.warn(`skipped unreadable image: ${file}`);
  }
}

entries.sort(([a], [b]) => a.localeCompare(b));

const body = entries.map(([url, w, h]) => `  "${url}": [${w}, ${h}],`).join("\n");
await writeFile(
  OUT_FILE,
  [
    "// AUTO-GENERATED by scripts/gen-image-dimensions.mjs — do not edit by hand.",
    "// Intrinsic pixel dimensions for every image under public/projects/.",
    "// Used to reserve layout space so lazy-loaded figures don't shift the page.",
    "",
    "export const IMAGE_DIMENSIONS: Record<string, readonly [number, number]> = {",
    body,
    "};",
    "",
  ].join("\n"),
  "utf8"
);

console.log(`wrote ${OUT_FILE} with ${entries.length} entries`);
